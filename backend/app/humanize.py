#: 表外兜底（**不调模型** ✗ —— 一句话说清"我看不出它具体干嘛，但它是条命令"✓）
_FALLBACK = "它想在本机跑一条命令 —— 具体做什么我看不出来，所以问你一句"


def _first_head(command: str) -> str:
    """命令的**第一个程序名**（剥掉引号/路径/变量赋值前缀 ✓ 认不出返回空串 ✓）。

    ★ 带引号的路径要**整词**认 ✗：`"/d/MiniMax Design/…/ffmpeg.exe" -i in out.mp4`
      里那条路径**含空格** ⇒ 按空白切会把 `ffmpeg.exe"` 弄丢一半 ✗
      （我第一版就是这样 ⇒ 认成了 `design/…`，一条 ffmpeg 命令说成了"认不出"✓）。
    """
    txt = str(command or "").strip()
    # 变量赋值前缀：`FF="…"` / `export X=y` —— 往下找到真正的程序 ✓
    for _ in range(4):
        new = re.sub(r'^\s*(?:export\s+|set\s+)?"?[A-Za-z_][A-Za-z0-9_]*=', "", txt)
        if new == txt:
            break
        txt = new
        # 跳过这个赋值剩下的部分（值可能带引号/空格）
        m = re.match(r"""^\s*(?:"[^"]*"|'[^']*'|\S+)""", txt)
        if not m:
            break
        txt = txt[m.end():]
    # ★ 先试"带引号的整词"（路径常含空格 ✓），再退回"到分隔符为止" ✓
    m = re.match(r"""^\s*"([^"]*)"|^\s*'([^']*)'""", txt)
    if m:
        tok = m.group(1) or m.group(2) or ""
    else:
        m2 = re.match(r"""^\s*([^\s"'|;&]+)""", txt)
        if not m2:
            return ""
        tok = m2.group(1)
    tok = tok.strip("\"'`")
    tok = tok.replace("\\", "/").rsplit("/", 1)[-1]
    return tok.lower()


def _heads(command: str) -> list[str]:
    """命令里**每一段**的首个程序名（多段命令只说人话要能说到重点 ✓）。

    ★ 分隔符用 **lookahead** ✓：`curl … | bash` 要切成 `curl …` 与 `| bash` ✓
      —— 把 `|` 吃掉的话，"管道到解释器"那条规则就永远看不到它 ✗（我第一版踩过 ✓）。
    """
    out: list[str] = []
    for part in re.split(r"\|\||&&|[;\n]|(?=[|])", str(command or "")):
        h = _first_head(part)
        if h and h not in out:
            out.append(h)
    return out


def plain_shell_summary(command: str) -> str:
    """一条 shell 命令 → **一句人话**（规则表打底 ✓ 表外兜底 ✓ 永不抛 ✗）。"""
    cmd = str(command or "")
    if not cmd.strip():
        return _FALLBACK
    low = cmd.lower()
    # ① 精确形态（最贴切 ✓ 优先）
    for kind, pat, text in _RULES:
        if kind == "frag" and pat in low:
            return text.replace("**", "")
    # ② 按**每一段**的程序名找（第一段命中即用 ✓ —— 那通常就是主动作 ✓）
    for h in _heads(cmd):
        for kind, pat, text in _RULES:
            if kind == "head" and pat == h:
                return text.replace("**", "")
    # ③ 兜底：至少把"是哪个程序"说出来（用户能自己判断 ✓）
    h = _heads(cmd)
    if h:
        return f"它想运行程序「{h[0]}」—— 具体做什么我看不出来，所以问你一句"
    return _FALLBACK


