_WHY_FALLBACK = "因为这条命令**可能有副作用**，按规矩要你点头"


def why_ask(reason: str | None) -> str:
    """把审批的**内部理由**翻成一句人话（认不出 ⇒ 通用兜底 ✓ 永不返回空 ✓）。"""
    txt = str(reason or "")
    if not txt.strip():
        return _WHY_FALLBACK
    for keys, human in _WHY_RULES:
        if any(k.lower() in txt.lower() for k in keys):
            return human.replace("**", "")
    return _WHY_FALLBACK


