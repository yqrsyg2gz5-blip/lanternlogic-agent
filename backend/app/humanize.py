def approval_summary(command: str, reason: str | None = None) -> str:
    """卡片那一句人话（工具名不是 shell 命令时也能用 ✓）。"""
    s = plain_shell_summary(command)
    if s == _FALLBACK and str(command or "").strip():
        # 表外还有"是哪个程序"这一档 ✓（至少让用户看出它要跑什么 ✓）
        return plain_shell_summary(command)
    return s


def approval_card(command: str, reason: str | None = None) -> dict[str, str]:
    """审批卡片的三个字段：`summary` / `why` / `command`（**add-only** ✓）。

    ★ `command` 一定**原样保留** ✗ —— 前端默认折叠可以 ✓ 删掉不行 ✓
      （用户要能查证"它到底想干嘛" ✓ 这是审批这件事的底线 ✓）。
    """
    return {
        "summary": approval_summary(command, reason),
        "why": why_ask(reason),
        "command": str(command or ""),
    }
