def suggest_roles(text: str, limit: int = 3) -> list[dict[str, object]]:
    """看这句话像是在干什么 ⇒ 推荐几个**天生干这个**的角色 ✓（返回空 = 没把握 ✓）。

    ★ 打分：命中的**关键词个数** ✓ 多者靠前 ✓ 同分按定义顺序（稳定 ✓ 不抖 ✓）。
    ★ 只做**字面命中** ✓ 不猜语义 ✗ —— 猜错会让用户觉得"这软件在瞎指挥"✓
      （真要做语义推荐，得走模型 ✓ 那是另一件事 ✓ 这里先给**可解释**的那种 ✓）
    """
    low = str(text or "").lower()
    if not low.strip():
        return []
    scored: list[tuple[int, int, str, list[str]]] = []
    for idx, (role, words) in enumerate(_TASK_HINTS):
        hits = [w for w in words if w.lower() in low]
        if hits:
            scored.append((len(hits), -idx, role, hits))
    scored.sort(reverse=True)
    out: list[dict[str, object]] = []
    for _n, _o, role, hits in scored[: max(1, limit)]:
        lib = ROLE_LIBRARY.get(role) or {}
        out.append({
            "role": role,
            "dept": lib.get("dept", ""),
            "summary": lib.get("summary", ""),
            "why": "因为你提到了「" + "」「".join(hits[:3]) + "」",
            "hits": hits[:5],
        })
    return out


