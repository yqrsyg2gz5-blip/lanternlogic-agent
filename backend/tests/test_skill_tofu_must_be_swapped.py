# -*- coding: utf-8 -*-
"""★★ 「方框（tofu）」必须一秒绕开 —— 真机事故烧掉 60% 的步数。

## 现场（2026-10-14 用户真机 task_20261014_345d630c，MiMo flash）

一条 20 秒卡点视频跑了 **73 分钟 / 368 步 / 360 步上限熔断 / 仍未做完**。
按动作类型归并步数：

```
   88 次  ★ 试字体 / 量文字宽度
   76 次  画一帧看效果          ← 配合试字体
   42 次  读图看效果
   52 次  ffmpeg 转码/抽帧      ← 配合看图
   ≈ 216 步 ≈ **60% 的步数**，全耗在"字体/符号显示不出来"这一件事上 ✗
```

## 它卡在哪：**一个箭头符号 `↔`**

它自己的看图记录（原话）：

```
10:32:22 「这是一个空心矩形方框。仔细观察可发现，图形没有"中间横线+两端箭头"
          的双向箭头特征，而是呈现出矩形的边框结构…」
10:32:48 「这个符号是**空心方框**（类似白色空心矩形的形状），并非双向箭头。」
```

**它把问题看得清清楚楚，然后选择了"去找一个能显示 ↔ 的字体"** ——
在 Windows 自带字体里翻了 88 次没翻到（雅黑/Arial 都没这个字形）✗

**而正确的动作是：换字符（`→` / `·` / `—`），或者干脆删掉它 —— 一秒的事** ✓

★ 同一个坑它掉了**两次**：
  · 中文字体（画到一半发现中文方框）→ 试了 29 次
  · `↔` 符号（发现方框）→ 试了 88 次
  · 根因：**技能里从来没写过"看到方框该怎么办"** ——
    只写了"交付时不许有方框"（结果要求），没写"出现方框时的第一步动作" ✗

## 本文件钉什么

1. 技能必须写明：**看到方框 ⇒ 换字符或删掉，禁止去找字体**（要写具体的替代字符）
2. 技能必须写明：**"找字体"这条路的代价**（实测 88 步没找到）
3. 环境体检必须**主动查**中文字体（而不是画到一半才发现）
"""
from __future__ import annotations

import pathlib
import re

SKILL = pathlib.Path(__file__).resolve().parents[2] / "backend" / "skills" / "卡点视频"


def _docs() -> str:
    return "\n".join(f.read_text("utf-8", errors="replace")
                     for f in sorted(SKILL.rglob("*.md")) if "node_modules" not in str(f))


def test_docs_say_to_swap_the_character_not_hunt_for_a_font():
    """★★ 核心：方框 ⇒ **换字符/删掉**，不许去找字体。"""
    txt = _docs()
    assert re.search(r"(方框|豆腐块|tofu)", txt), "技能里没提「方框」这件事 ✗"
    # 必须有"换字符"这个动作，且和"别找字体"配套
    assert re.search(r"(换字符|换符号|改成.{0,6}(符号|字符)|删掉.{0,6}符号)", txt), (
        "技能里没写「看到方框就换字符」⇒ 模型会去死磕字体 ✗\n"
        "  实测：它为了显示 `↔` 翻了 88 次字体没翻到，烧掉 60% 的步数 ✗"
    )
    assert re.search(r"(别|不要|禁止|不许).{0,12}(找|换|试).{0,6}字体", txt) or \
        re.search(r"(找字体|换字体).{0,20}(没用|白费|找不到|别)", txt), (
        "技能里没写「别去找字体」⇒ 模型会一遍遍试字体 ✗"
    )


def test_docs_give_concrete_safe_substitutes():
    """光说"换字符"不够 —— 要给出**具体能用的替代字符**（否则它又乱试）。"""
    txt = _docs()
    subs = ["→", "·", "—", "-", "|"]
    hit = [s for s in subs if s in txt]
    assert len(hit) >= 2, (
        f"没给出足够的具体替代字符（找到 {hit}）⇒ 模型还得自己试 ✗\n"
        "  应该直接列出：→ · — | 这些一定能显示的"
    )


def test_docs_warn_about_the_step_cost_of_font_hunting():
    """要说清代价（模型才有理由遵守）——这次的数字很有说服力。"""
    txt = _docs()
    assert re.search(r"88\s*次|60%.{0,20}步数|一半.{0,6}步数|烧掉.{0,10}步", txt), (
        "没写清「死磕字体」的代价 ⇒ 模型感受不到严重性 ✗\n"
        "  实测：88 次试字体 / 占全部步数 60% / 整条任务熔断 ✗"
    )


def test_preflight_checks_chinese_fonts_upfront():
    """★ 环境体检要**主动**查中文字体 —— 而不是画到一半才发现方框。

    ★ 判据取**第 0 步的标题行**那一段（`### 第 0 步 …`）——
      不能只找"环境体检"四个字：总览表里也提到了它，会定位到表头去 ✗（本班踩过）
    """
    txt = _docs()
    m = re.search(r"###\s*第\s*0\s*步", txt)
    assert m, "找不到「第 0 步」的标题行 ✗"
    # 从第 0 步标题起，到第 1 步标题止
    m2 = re.search(r"###\s*第\s*1\s*步", txt[m.end():])
    seg = txt[m.start(): m.end() + (m2.start() if m2 else 6000)]
    assert re.search(r"(字体|font|中文.{0,6}(渲染|显示))", seg), (
        "第 0 步「环境体检」里**没有字体检查** ⇒ 模型画到一半才发现中文/符号是方框，"
        "然后开始死磕 ✗\n"
        "  实测：这一个疏漏让整条任务多烧了 60% 的步数（88 次试字体）"
    )
